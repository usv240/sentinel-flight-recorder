def _check_metric_conditions(snapshot: dict, decision_type: str) -> list:
    """
    Check current metrics against safe thresholds.
    Returns list of blocking conditions (things that make this decision risky right now).
    """
    conditions = []
    nps = snapshot.get("nps")
    churn = snapshot.get("churn_rate")
    mrr = snapshot.get("mrr")
    runway = snapshot.get("runway_months")

    if decision_type == "pricing":
        if nps is not None:
            try:
                nps = float(nps)
                if nps < _THRESHOLDS["nps"]["critical"]:
                    conditions.append(f"NPS={nps:.0f} is CRITICAL (below {_THRESHOLDS['nps']['critical']} — pricing decisions here are high-risk in 81% of cases)")
                elif nps < _THRESHOLDS["nps"]["warning"]:
                    conditions.append(f"NPS={nps:.0f} is below warning threshold ({_THRESHOLDS['nps']['warning']}) — customers are already unhappy")
                elif nps < _THRESHOLDS["nps"]["safe"]:
                    conditions.append(f"NPS={nps:.0f} is below safe threshold ({_THRESHOLDS['nps']['safe']}) for price increases")
            except (TypeError, ValueError):
                pass

        if churn is not None:
            try:
                churn = float(churn)
                if churn > _THRESHOLDS["churn_rate"]["critical"]:
                    conditions.append(f"Churn={churn:.1%} exceeds CRITICAL threshold ({_THRESHOLDS['churn_rate']['critical']:.0%}) — pricing increase accelerates exits")
                elif churn > _THRESHOLDS["churn_rate"]["warning"]:
                    conditions.append(f"Churn={churn:.1%} already elevated (above {_THRESHOLDS['churn_rate']['warning']:.0%} warning threshold)")
            except (TypeError, ValueError):
                pass

    elif decision_type == "hiring":
        if runway is not None:
            try:
                runway = float(runway)
                if runway < 6:
                    conditions.append(f"Runway={runway:.1f} months is CRITICAL — new hires add burn before they add value")
                elif runway < 8:
                    conditions.append(f"Runway={runway:.1f} months — senior hire may constrain future options")
            except (TypeError, ValueError):
                pass

    elif decision_type == "product":
        if nps is not None:
            try:
                nps = float(nps)
                if nps < 40:
                    conditions.append(f"NPS={nps:.0f} — customers already dissatisfied, feature removal risks further erosion")
            except (TypeError, ValueError):
                pass

    return conditions


def _match_historical_patterns(snapshot: dict, decision_type: str) -> list:
    """
    Find historical patterns that match current conditions.
    Returns matching patterns sorted by frequency (most dangerous first).
    """
    patterns = _HISTORICAL_PATTERNS.get(decision_type, [])
    matches = []

    nps = None
    churn = None
    runway = None
    try:
        nps = float(snapshot.get("nps") or 0)
        churn = float(snapshot.get("churn_rate") or 0)
        runway = float(snapshot.get("runway_months") or 99)
    except (TypeError, ValueError):
        pass

    for p in patterns:
        conds = p.get("conditions", {})
        matched = True

        if "nps_max" in conds and nps is not None and nps > conds["nps_max"]:
            matched = False
        if "churn_rate_min" in conds and churn is not None and churn < conds["churn_rate_min"]:
            matched = False
        if "runway_months_max" in conds and runway is not None and runway > conds["runway_months_max"]:
            matched = False

        if matched:
            matches.append(p)

    return sorted(matches, key=lambda x: x["frequency"], reverse=True)


def _calculate_risk_score(blocking_conditions: list, pattern_matches: list) -> float:
    """
    Calculate a 0-1 risk score.
    - Blocking conditions each add 0.2-0.4 depending on severity
    - Pattern matches weighted by their historical frequency
    """
    score = 0.0

    # Conditions contribute to risk
    for c in blocking_conditions:
        if "CRITICAL" in c:
            score += 0.35
        elif "warning" in c.lower() or "elevated" in c.lower():
            score += 0.20
        else:
            score += 0.10

    # Pattern matches weighted by their historical frequency
    for p in pattern_matches:
        score += p["frequency"] * 0.4

    return round(min(score, 1.0), 2)


def _risk_level(score: float) -> str:
    if score >= 0.65:
        return "high"
    elif score >= 0.35:
        return "medium"
    else:
        return "low"


def _build_alternatives(decision_type: str, snapshot: dict) -> list:
    """Build context-aware alternative recommendations."""
    templates = _ALTERNATIVES.get(decision_type, [])
    alts = []
    for t in templates[:3]:
        # Fill in any template placeholders
        alt = t
        nps = snapshot.get("nps", 0)
        try:
            nps = float(nps)
            # Rough estimate: 2 points NPS per week recovery
            weeks = max(1, round((45 - nps) / 2))
            alt = alt.replace("{weeks}", str(weeks))
        except Exception:
            alt = alt.replace("{weeks}", "6-8")

        churn = snapshot.get("churn_rate", 0)
        try:
            # Suggest half the proposed increase
            alt = alt.replace("{half_pct}", "10")
        except Exception:
            alt = alt.replace("{half_pct}", "10")

        alts.append(alt)
    return alts


async def run_precheck(
    decision_text: str,
    decision_type: str,
    snapshot: dict,
    scenario: str = None,
) -> dict:
    """
    Main precheck function. Returns full risk analysis.
    Called before a decision is logged to the database.
    """
    # Enrich snapshot with live BigQuery data if available
    if scenario:
        try:
            from .bigquery_pipeline import get_real_time_series, get_current_metrics_from_ts
            ts = await get_real_time_series(scenario)
            if ts:
                live = get_current_metrics_from_ts(ts)
                # Merge: prefer live BigQuery values over cached snapshot
                snapshot = {**snapshot, **live}
        except Exception:
            pass

    blocking_conditions = _check_metric_conditions(snapshot, decision_type)
    # Include any snapshot flags (survey data, trend warnings) as blocking conditions
    for flag in snapshot.get("_flags", []):
        blocking_conditions.append(flag)
    pattern_matches = _match_historical_patterns(snapshot, decision_type)
    risk_score = _calculate_risk_score(blocking_conditions, pattern_matches)
    level = _risk_level(risk_score)
    alternatives = _build_alternatives(decision_type, snapshot)

    # Always run Gemini so the decision text itself is evaluated
    gemini_advice = ""
    try:
        from .gemini_client import generate
        flags_text = "\n".join(f"- {f}" for f in snapshot.get("_flags", [])) or "- None"
        prompt = f"""You are SENTINEL. A business decision is being evaluated before logging.

DECISION: "{decision_text}"
DECISION TYPE: {decision_type}
RISK SCORE: {risk_score:.0%} ({level.upper()} RISK)
BLOCKING CONDITIONS:
{chr(10).join(f'- {c}' for c in blocking_conditions) or '- None'}
DATA FLAGS (signals present in the business at decision time):
{flags_text}
HISTORICAL MATCHES: {len(pattern_matches)} pattern(s) found
MOST DANGEROUS PATTERN: {pattern_matches[0]['description'] if pattern_matches else 'None'}

Write ONE sentence: the most important thing the decision-maker should know before proceeding.
Be specific. Reference the exact decision text and the most critical flag or metric. No hedging."""

        gemini_advice = await generate(prompt)
    except Exception as e:
        log.error(f"Gemini precheck advice failed: {e}")

    # Estimated ARR impact from worst matching pattern
    worst_pattern = pattern_matches[0] if pattern_matches else {}
    mrr = float(snapshot.get("mrr") or 0)
    arr = mrr * 12
    estimated_impact_low = worst_pattern.get("avg_arr_impact", 0) if worst_pattern else 0
    estimated_impact_high = estimated_impact_low * 1.5 if estimated_impact_low else 0

    return {
        "risk_level": level,
        "risk_score": risk_score,
        "proceed_recommended": level == "low",
        "blocking_conditions": blocking_conditions,
        "pattern_matches": [
            {
                "pattern": p["description"],
                "historical_failure_rate": p["frequency"],
                "outcome": p["outcome_description"],
                "n_examples": p["examples"],
            }
            for p in pattern_matches[:3]
        ],
        "estimated_arr_impact": {
            "low": int(estimated_impact_low),
            "high": int(estimated_impact_high),
            "currency": "USD",
        },
        "alternative_recommendations": alternatives,
        "gemini_advice": gemini_advice,
        "current_metrics": {
            "nps": snapshot.get("nps"),
            "churn_rate": snapshot.get("churn_rate"),
            "mrr": snapshot.get("mrr"),
            "runway_months": snapshot.get("runway_months"),
        },
        "safe_to_proceed_when": _safe_conditions(decision_type),
    }


def _safe_conditions(decision_type: str) -> list:
    if decision_type == "pricing":
        return [
            "NPS > 45 (currently indicates healthy customer satisfaction)",
            "Churn rate < 6% (stable retention baseline)",
            "MRR growth positive for 2+ consecutive months",
        ]
    elif decision_type == "hiring":
        return ["Runway > 12 months", "Current team at capacity (utilization > 85%)"]
    elif decision_type == "product":
        return ["NPS > 45", "Feature usage < 5% of active accounts (for removals)"]
    return ["No critical flags in current metrics"]
